def _fmt_money(v) -> str:
    return f"${v:,.2f}" if v is not None else "-"


def build(findings: dict, out_path: Path) -> None:
    f = findings
    bc = f["booking_curve_by_operator"]
    wd = f["booking_curve_weekday_weekend"]
    fg = f["fare_gap_regional_vs_greyhound"]
    lf = f["leader_follower_regional_vs_greyhound"]
    ov = f["was_nyc_overlap_status"]
    pc = f["persona_commuter"]
    pb = f["persona_business_traveler"]
    ps = f["persona_student"]
    pf = f["persona_family"]
    recs = f.get("recommendations", [])

    html = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<title>PHL-NYP Pricing Analysis</title><style>{CSS}</style></head><body>
<header class="top"><div class="wrap">
  <h1>PHL &harr; NYP Pricing Intelligence</h1>
  <p>Team 2 &middot; BUDT770 Capstone &middot; generated {f['generated_at'][:16].replace('T', ' ')} UTC
     &middot; regenerate any time with <code>python tools/run_analysis.py</code></p>
  <div class="stat-row">
    <div class="stat"><div class="n">{f['rows_clean']:,}</div><div class="l">clean priced rows</div></div>
    <div class="stat"><div class="n">{f['snapshot_days']}</div><div class="l">snapshot days collected</div></div>
    <div class="stat"><div class="n">{f['travel_dates_in_window']}</div><div class="l">travel dates monitored</div></div>
    <div class="stat"><div class="n">{bc['max_dbd_in_data']}</div><div class="l">max days-before-departure seen</div></div>
  </div>
</div></header>
<div class="wrap">
"""

    if f["thin_or_missing_days"]:
        html += (f'<div class="callout warn">Data quality: thin/partial '
                 f'snapshot day(s) &mdash; {", ".join(f["thin_or_missing_days"])}. '
                 f'See docs/DATA_DICTIONARY.md.</div>')

    # --- Recommendations: the sponsor-facing output, up top -----------------
    if recs:
        cards = ""
        for i, r in enumerate(recs, 1):
            cards += f"""
    <div class="persona-card">
      <h3>{i}. {r['segment']}</h3>
      <div class="stat-line"><b>Action:</b> {r['action']}</div>
      <div class="stat-line"><b>Expected impact:</b> {r['expected_impact']}</div>
      <div class="stat-line"><b>Trade-off:</b> {r['trade_off']}</div>
      <div class="stat-line" style="color:var(--muted);"><b>Risk:</b> {r['risk']}</div>
    </div>"""
        html += f"""
<section>
  <div class="tag">Recommendations</div>
  <h2>What this data says Amtrak should actually do</h2>
  <p class="lede">Every number below traces to real fare data or a cited elasticity
     estimate (see analysis/elasticity.py) &mdash; nothing here is invented, and where
     no sourced number exists the risk is stated qualitatively rather than guessed.</p>
  <div class="persona-grid">{cards}
  </div>
</section>
"""

    # --- Q2: booking behavior ------------------------------------------------
    html += f"""
<section>
  <div class="tag">Core question 2</div>
  <h2>How does fare behave by booking window, day, and time?</h2>
  <p class="lede">Daily snapshots, derived days-before-departure (DBD) &mdash;
     no milestone is hard-coded, so this chart extends on its own as more days are collected.</p>
  <div class="callout">Weekday median <b>{_fmt_money(wd['weekday_median'])}</b> vs
     weekend median <b>{_fmt_money(wd['weekend_median'])}</b>
     ({wd['gap_pct']:+.1f}% weekday-to-weekend gap).</div>
  <div class="chart-grid">
    <div class="chart-card"><img src="figures/booking_curve_by_operator.png">
      <div class="cap">Acela &gt; Regional &gt; Keystone holds across the booking window &mdash;
      the internal Amtrak pricing hierarchy the sponsor asked about.</div></div>
    <div class="chart-card"><img src="figures/booking_curve_weekday_weekend.png">
      <div class="cap">Weekday (business) vs weekend (leisure) booking curves.</div></div>
    <div class="chart-card"><img src="figures/amtrak_fare_heatmap.png">
      <div class="cap">When Amtrak fares peak, by day of week and departure hour.</div></div>
  </div>
</section>

<section>
  <div class="tag">Core question 3</div>
  <h2>Where does rail win or lose on value against bus?</h2>
  <p class="lede">Same-source fares only (api.wanderu.com for both rail and bus) &mdash;
     mixing sources would bias this by the ~20% aggregator markup documented in
     docs/DATA_DICTIONARY.md.</p>
  <div class="callout">{fg['rail_service']} vs {fg['bus_benchmark']}: median gap
     <b>{_fmt_money(fg['median_gap_usd'])}</b>. Rail is cheaper at DBD
     {', '.join(map(str, fg['rail_cheaper_at_dbd'])) if fg['rail_cheaper_at_dbd'] else 'never, in this window'}.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/fare_gap_regional_vs_greyhound.png">
    <div class="cap">Red = rail costs more · green = rail is cheaper, by DBD.</div></div></div>
</section>

<section>
  <div class="tag">Core question 4</div>
  <h2>Does one mode lead or follow the other's price changes?</h2>
  <div class="callout {'good' if lf.get('significant') and lf.get('repeats_across_dates') else 'warn'}">
     {lf['n_snapshot_days']} snapshot days available &mdash; reading:
     <b>{lf.get('reading', 'n/a')}</b>.
     Statistically significant (p&lt;0.05): <b>{lf.get('significant', 'n/a')}</b>.
     Repeats across first/second half of the window: <b>{lf.get('repeats_across_dates', 'not enough days yet')}</b>.
     A lead/lag is only named on this dashboard when both of those are true.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/leader_follower_regional_vs_greyhound.png">
    <div class="cap">Cross-correlation of day-over-day % fare change, by lag (days).</div></div></div>
</section>

<section>
  <div class="tag">Depth add-on</div>
  <h2>Revenue sensitivity under sourced price elasticity</h2>
  <p class="lede">We checked for a real demand/quantity signal in our own data first &mdash;
     Wanderu's seats_remaining field turned out to be a placeholder (always the literal
     value 1 across 225k+ rows), and FlixBus's sold_out flag is the only real one, bus-only.
     So this applies SOURCED elasticity estimates from the transportation economics
     literature to our own real fare data, reported as a range under uncertainty, never
     a single invented number &mdash; see analysis/elasticity.py for full citations.</p>
  <div class="callout">Rail own-price elasticity: <b>-0.32 to -1.20</b> (FHWA literature
     review). Acela assigned the less-elastic end per a CBO finding that 1970s Amtrak
     demand was inelastic specifically for Northeast Corridor business travel &mdash;
     flagged here as dated, pre-deregulation evidence, not a modern point estimate.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/revenue_elasticity_scenarios.png">
    <div class="cap">Floating bars show the full range implied by the sourced elasticity
    estimates &mdash; the range itself is the finding.</div></div></div>
</section>
"""

    # --- additional presentation figures ------------------------------------
    vol = f["fare_volatility_by_group"]["table"]
    sav = f["book_ahead_savings"]["table"]
    sold_out = f.get("flixbus_sold_out_by_dbd")
    cov = f["collection_coverage_by_source"]
    best_sav = max(sav, key=lambda r: r["savings_usd"]) if sav else None
    html += f"""
<section>
  <div class="tag">Depth add-on</div>
  <h2>Pricing behavior, beyond the median</h2>
  <p class="lede">Three more concrete questions a rider or a pricing team would
     actually ask, built from data already collected above.</p>
  <div class="chart-grid">
    <div class="chart-card"><img src="figures/fare_volatility_by_group.png">
      <div class="cap">{vol[0]['group'] if vol else ''} reprices the least day-to-day;
      {vol[-1]['group'] if vol else ''} reprices the most &mdash; same DBD-band method as
      the leader/follower signal above, so trend and real volatility aren't conflated.</div></div>
    <div class="chart-card"><img src="figures/book_ahead_savings.png">
      <div class="cap">{f"Biggest payoff: {best_sav['group']} riders save ${best_sav['savings_usd']} ({best_sav['savings_pct']}%) booking ahead." if best_sav else ''}</div></div>
    <div class="chart-card"><img src="figures/fare_distribution_by_group.png">
      <div class="cap">Full fare spread at a fixed booking window &mdash; two groups can
      share a median and still differ a lot in how predictable that price is.</div></div>
  </div>
</section>
"""
    if sold_out:
        html += f"""
<section>
  <div class="tag">Depth add-on</div>
  <h2>The one real demand signal in this project</h2>
  <p class="lede">Every other "demand" number on this page is a modeled or sourced
     estimate (see the revenue sensitivity section above) because we don't have
     real booking volume data. This is the one exception: FlixBus/Greyhound's own
     sold_out flag, a real observed outcome, not a model.</p>
  <div class="callout">Sold-out rate peaks at <b>{sold_out['peak_sold_out_pct']}%</b>
     around <b>{sold_out['peak_sold_out_dbd']} days</b> before departure.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/flixbus_sold_out_by_dbd.png"></div></div>
</section>
"""
    html += f"""
<section>
  <div class="tag">Transparency</div>
  <h2>Collection scale and reliability</h2>
  <p class="lede">Not a pricing finding &mdash; a look at the collection process itself,
     so a reader can see this is built on {cov['total_rows']:,} real observed rows
     across {cov['snapshot_days']} days, not a handful of samples.</p>
  <div class="chart-grid"><div class="chart-card"><img src="figures/collection_coverage_by_source.png"></div></div>
</section>

<section>
  <div class="tag">Deferred, sponsor-flagged</div>
  <h2>WAS&ndash;NYC inventory overlap <span class="pill pending">waiting on data</span></h2>
  <p class="lede">PHL-NYP and WAS-NYP share physical seats on the same through-train.
     This section activates automatically &mdash; no code change &mdash; the moment a
     WAS&harr;NYP source starts writing into the same fares table.</p>
  <div class="callout warn">Route pairs currently in data: {', '.join(ov['route_pairs_in_data'])}.
     Next step: {ov['next_step']}</div>
</section>

<section>
  <div class="tag">Personas</div>
  <h2>Four lenses over the same dataset</h2>
  <p class="lede">Student and Family are the team's original personas; Commuter and
     Business Traveler were added at the sponsor mentor's suggestion.</p>
  <div class="persona-grid">
    <div class="persona-card"><h3>Commuter</h3>
      <img src="figures/persona_commuter.png" style="width:100%;border-radius:6px;margin-bottom:8px;">
      <div class="stat-line">Weekly cost, 10 weekday peak trips:
        <b>{_fmt_money(pc['weekly_rail_cost'])}</b> rail vs
        <b>{_fmt_money(pc['weekly_bus_cost'])}</b> {pc['cheapest_bus_operator']}</div>
      <div class="stat-line">Rail premium: <b>{pc['rail_premium_pct']}%</b></div></div>

    <div class="persona-card"><h3>Business Traveler</h3>
      <img src="figures/persona_business_traveler.png" style="width:100%;border-radius:6px;margin-bottom:8px;">
      <div class="stat-line">Acela <b>{_fmt_money(pb['acela_median_fare'])}</b> vs Regional
        <b>{_fmt_money(pb['regional_median_fare'])}</b> (&le;5 DBD)</div>
      <div class="stat-line">Pays <b>{_fmt_money(pb['fare_premium_usd'])}</b> more to save
        <b>{pb['time_saved_min']:.0f} min</b> &mdash; implied
        <b>{_fmt_money(pb['implied_usd_per_minute_saved'])}/minute</b></div></div>

    <div class="persona-card"><h3>Student <span style="font-weight:400;color:var(--muted);font-size:12px;">(group of {ps['group_size']})</span></h3>
      <img src="figures/persona_student.png" style="width:100%;border-radius:6px;margin-bottom:8px;">
      <div class="stat-line">Cheapest bus, per person: <b>{_fmt_money(min(ps['fares_round_trip_per_person'].values()) if ps['fares_round_trip_per_person'] else None)}</b></div>
      <div class="stat-line">Modeled rental, per person: <b>{_fmt_money(ps['rental_per_person_modeled'])}</b>
        &mdash; cheapest option: <b>{'rental' if ps['rental_is_cheapest'] else 'rail/bus'}</b></div></div>

    <div class="persona-card"><h3>Family <span style="font-weight:400;color:var(--muted);font-size:12px;">(group of {pf['group_size']})</span></h3>
      <img src="figures/persona_family.png" style="width:100%;border-radius:6px;margin-bottom:8px;">
      <div class="stat-line">Modeled rental, per person: <b>{_fmt_money(pf['rental_per_person_modeled'])}</b>
        &mdash; cheapest option: <b>{'rental' if pf['rental_is_cheapest'] else 'rail/bus'}</b></div>
      <div class="stat-line" style="color:var(--muted);font-size:12px;">Rental figures are MODELED
        (documented formula), not scraped &mdash; see analysis/driving.py.</div></div>
  </div>
</section>
"""

    # --- Census ---------------------------------------------------------------
    if f.get("census_configured") and f.get("census_affordability_rows"):
        dist = f.get("census_income_distribution", {})
        summary = f.get("census_affordability_summary", {})
        rows = "".join(f"<tr><td>{k}</td><td>{v}%</td></tr>" for k, v in summary.items())
        html += f"""
<section>
  <div class="tag">Sponsor-suggested</div>
  <h2>Income-based affordability <span class="pill ready">live ACS data</span></h2>
  <p class="lede">An affordability lens, not a fitted demand curve &mdash; we have no real
     booking/elasticity data. Source: Census ACS 5-year estimates (2023), table B19001.</p>
  <div class="callout">Philadelphia: <b>{dist.get('phl_pct_households_under_35k')}%</b> of
     households earn under $35k/yr. NYC: <b>{dist.get('nyc_pct_households_under_35k')}%</b>.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/census_income_distribution.png">
    <div class="cap">Household income distribution, Philadelphia vs NYC.</div></div></div>
  <table><thead><tr><th>Metro / service</th><th>% of households where round-trip fare &gt; 2% of monthly income</th></tr></thead>
  <tbody>{rows}</tbody></table>
</section>
"""
        sp = f.get("spending_power")
        if sp:
            html += f"""
<section>
  <div class="tag">Depth add-on</div>
  <h2>Spending power: who does the fare actually cost more, in real terms?</h2>
  <p class="lede">Nominal income understates Philadelphia and overstates NYC &mdash; a
     dollar buys less in New York. Adjusted using BEA Regional Price Parities
     (all items, 2023 vintage, national average = 100): Philadelphia
     <b>{sp['regional_price_parity']['Philadelphia']}</b>, New York City
     <b>{sp['regional_price_parity']['New York City']}</b>. NYC's figure is a
     household-weighted approximation across its 5 boroughs, not a single
     Census-published value.</p>
  <div class="callout">NYC households earn <b>{sp['nyc_nominal_premium_pct']:+.1f}%</b> more
     than Philadelphia's, nominally. After adjusting for cost of living, the real gap
     is only <b>{sp['nyc_real_premium_pct']:+.1f}%</b>.</div>
  <div class="chart-grid"><div class="chart-card"><img src="figures/spending_power.png">
    <div class="cap">Nominal vs cost-of-living-adjusted median household income.</div></div></div>
</section>
"""
    else:
        html += f"""
<section>
  <div class="tag">Sponsor-suggested</div>
  <h2>Income-based affordability <span class="pill pending">not configured</span></h2>
  <p class="lede">{f.get('census_reason', 'No Census API key set.')}
     Add one free (2-minute signup) and this section activates with no code change &mdash;
     see analysis/census.py.</p>
</section>
"""

    html += f"""
<footer>Every chart regenerates from data/exports/fares_latest.parquet &mdash;
run <code>python run_daily.py</code> then <code>python tools/run_analysis.py</code>
to refresh with today's data. Raw findings: <a href="findings.json">findings.json</a>
&middot; narrative version: <a href="findings.md">findings.md</a></footer>
</div></body></html>"""

    out_path.write_text(html, encoding="utf-8")
