"""One-page HTML dashboard: every chart, organized by the framing doc's own
core questions, with plain-English callouts pulled from the findings dict -
not a raw JSON dump.

Regenerated by report.run() on every call, so it always reflects whatever is
currently in data/exports/fares_latest.parquet. There is nothing in here
that assumes a specific day count or date - a teammate opens
reports/dashboard.html, sees today's numbers, and it looks the same whether
that's 24 snapshot days or 45.
"""
